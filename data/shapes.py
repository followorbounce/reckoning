"""Plane figures and solids.

Formulas are expression strings in a syntax that is valid in both Python and
JavaScript (operators + - * / **, functions sqrt sin cos tan asin acos atan,
constant PI; angles given in degrees are converted with `rad`). `let` defines
intermediate values in order. The same strings are evaluated by the build-time
checks (tests/check_shapes.py, against Monte Carlo and numerical integration) and
by the live figure in the browser, so what is checked is exactly what is shown.

`tex` is the formula as printed (KaTeX). `topo` holds the topology lens:
holes (genus), cavities, the Euler characteristic of the boundary surface
(solids) or of the region itself (plane figures), and V/E/F for polyhedra.
"""


def P(key, label, default, lo, hi, step=0.1, unit='len'):
    return {'key': key, 'label': label, 'default': default, 'min': lo, 'max': hi, 'step': step, 'unit': unit}


def Q(sym, name, expr, tex, kind='len', checked=True, approx=False):
    return {'sym': sym, 'name': name, 'expr': expr, 'tex': tex, 'kind': kind, 'checked': checked, 'approx': approx}


